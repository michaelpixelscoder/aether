import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const author=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(author,'../../..');
const args=process.argv.slice(2),arg=name=>args.includes(name)?path.resolve(args[args.indexOf(name)+1]):undefined;
const input=arg('--input-world')??path.join(author,'history/r56-world');
const output=arg('--output-world')??path.join(root,'assets/world');
const reportFile=arg('--report')??path.join(author,'proofs/r56-patch.json');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const sourceSha='087deb4c68767e876653edc1b1fd0890b0ce5cb051beb5a29d03de718806b365';
const imageUri=`textures/${sourceSha}.png`,scale=2.1/(4*.11);
const png=fs.readFileSync(path.join(author,'source/ground-r60-native.png'));
assert.equal(sha(png),sourceSha);
assert.equal(sha(fs.readFileSync(path.join(output,imageUri))),sourceSha);
const generation=JSON.parse(fs.readFileSync(path.join(author,'source/generation.json')));
assert.equal(generation.sha256,sourceSha);assert.equal(generation.tool,'image_gen.imagegen built-in');
assert.equal(generation.transparent_background,false);assert(!generation.resampled&&!generation.retouched);
const report=JSON.parse(fs.readFileSync(reportFile));
assert.equal(report.source_png_sha256,sourceSha);
assert.equal(report.patch_source_sha256,sha(fs.readFileSync(path.join(author,'patch_ground.py'))));
const read=file=>{const raw=fs.readFileSync(file);assert.equal(raw.readUInt32LE(0),0x46546c67);assert.equal(raw.readUInt32LE(4),2);assert.equal(raw.readUInt32LE(8),raw.length);const n=raw.readUInt32LE(12);assert.equal(raw.readUInt32LE(16),0x4e4f534a);assert.equal(raw.readUInt32LE(24+n),0x004e4942);assert.equal(raw.readUInt32LE(20+n)+28+n,raw.length);return{raw,doc:JSON.parse(raw.subarray(20,20+n)),bin:raw.subarray(28+n)};};
const files=['dawn.glb','dawn-lod.glb','dawn-watch.glb','dawn-watch-lod.glb'];
const results=[];
for(const file of files){
 const before=read(path.join(input,file)),after=read(path.join(output,file));
 assert(after.bin.equals(before.bin),'Every BIN byte unchanged, including UV, COLOR_0 if any, geometry and indices');
 const old=before.doc,doc=after.doc;
 const ids=old.materials.map((m,i)=>m.name.startsWith('12 | Surface biome')?i:-1).filter(i=>i>=0);assert.equal(ids.length,1);const target=ids[0];
 const material=structuredClone(doc.materials[target]),oldMaterial=old.materials[target];
 const pbr=material.pbrMetallicRoughness,oldPbr=oldMaterial.pbrMetallicRoughness;
 assert.deepEqual(pbr.baseColorFactor,[1,1,1,1]);
 const info=pbr.baseColorTexture;
 assert.equal(info.index,old.textures.length);
 assert.deepEqual(info.extensions.KHR_texture_transform,{scale:[scale,scale]});
 const targetTexture=doc.textures.at(-1),expectedTexture=structuredClone(old.textures[oldPbr.baseColorTexture.index]);
 expectedTexture.source=old.images.length;expectedTexture.name='R60 grass moss original PNG';assert.deepEqual(targetTexture,expectedTexture);
 pbr.baseColorTexture=structuredClone(oldPbr.baseColorTexture);
 if('baseColorFactor' in oldPbr)pbr.baseColorFactor=oldPbr.baseColorFactor;else delete pbr.baseColorFactor;
 assert.deepEqual(material,oldMaterial,'Target roughness/normal/metallic/all unrelated fields preserved');
 const recovered=structuredClone(doc);recovered.materials[target]=structuredClone(oldMaterial);
 assert.equal(doc.images.length,old.images.length+1);
 assert.deepEqual(doc.images.slice(0,-1),old.images);
 assert.deepEqual(doc.images.at(-1),{mimeType:'image/png',name:'R60 natural grass moss native',uri:imageUri});
 recovered.images=structuredClone(old.images);
 assert.equal(doc.textures.length,old.textures.length+1);assert.deepEqual(doc.textures.slice(0,-1),old.textures);recovered.textures=structuredClone(old.textures);
 const extensions=[...(old.extensionsUsed??[])];if(!extensions.includes('KHR_texture_transform'))extensions.push('KHR_texture_transform');
 assert.deepEqual(doc.extensionsUsed,extensions);
 if(old.extensionsUsed)recovered.extensionsUsed=old.extensionsUsed;else delete recovered.extensionsUsed;
 assert.deepEqual(recovered,old,'All11 other HD materials,9 other LOD materials, all meshes/accessors/nodes/images/history extras exact');
 const pinned=report.files.find(f=>f.file===file);assert(pinned);assert.equal(pinned.input_sha256,sha(before.raw));assert.equal(pinned.output_sha256,sha(after.raw));assert.equal(pinned.bytes,after.raw.length);
 results.push({file,input_sha256:sha(before.raw),output_sha256:sha(after.raw),bin_exact:true,all_other_json_exact:true});
}
const originalManifest=JSON.parse(fs.readFileSync(path.join(input,'manifest.json'))),manifest=JSON.parse(fs.readFileSync(path.join(output,'manifest.json'))),recoveredManifest=structuredClone(manifest);
for(const kind of ['dawn','dawn-watch'])for(const level of ['high','lod']){
 const file=level==='high'?`${kind}.glb`:`${kind}-lod.glb`,raw=fs.readFileSync(path.join(output,file));
 assert.equal(manifest[kind][level].sha256,sha(raw));assert.equal(manifest[kind][level].bytes,raw.length);
 recoveredManifest[kind][level].sha256=originalManifest[kind][level].sha256;recoveredManifest[kind][level].bytes=originalManifest[kind][level].bytes;
}
assert.deepEqual(recoveredManifest,originalManifest,'Only four asset SHA/bytes records changed; all historical manifest metadata exact');
console.log(JSON.stringify({passed:true,source_png_byte_exact:true,uv_and_geometry_exact:true,target_material_only:true,historical_manifest_metadata_exact:true,results,native_compile:'PENDING',mip_count:1,performance:'UNMEASURED'}));
